-- Development passwords, scoped to the local Docker database.
CREATE ROLE app_owner LOGIN PASSWORD 'local-owner' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE app_readwrite LOGIN PASSWORD 'local-readwrite' NOSUPERUSER NOCREATEDB NOCREATEROLE;
CREATE ROLE app_readonly LOGIN PASSWORD 'local-readonly' NOSUPERUSER NOCREATEDB NOCREATEROLE;
ALTER SCHEMA public OWNER TO app_owner;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO app_readwrite, app_readonly;
ALTER DEFAULT PRIVILEGES FOR ROLE app_owner IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO app_readwrite;
ALTER DEFAULT PRIVILEGES FOR ROLE app_owner IN SCHEMA public
    GRANT SELECT ON TABLES TO app_readonly;
